// Generates src/lib/studio/pages-notes-en.ts: a slim slug -> sourceNotes map
// built from pages.ts.
//
// Why: the [lang]/[slug] page node reads the English twin's sourceNotes as the
// fallback for translated pages' sources block (pages-translated carries none).
// That fallback statically pulled the whole EN pages chunk (155KB) into every
// translated page bundle (found by the 2026-11-24 resource/weight sweep). The
// slim module carries only the notes (~20KB), so the full chunk is no longer
// in the translated routes' graph.
//
// Run modes:
//   node scripts/gen-en-notes.mjs            write the file if it differs
//   node scripts/gen-en-notes.mjs --check    exit 1 if the file is stale
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.dirname(fileURLToPath(import.meta.url)) + '/..';
const OUT = path.join(root, 'src/lib/studio/pages-notes-en.ts');

// Node strips TS types natively (pages.ts only uses type-only imports).
const { pages } = await import(path.join(root, 'src/lib/studio/pages.ts'));

const entries = pages
	.filter((p) => p.sourceNotes && p.sourceNotes.length)
	.map((p) => `\t"${p.slug}": ${JSON.stringify(p.sourceNotes)},`)
	.join('\n');

const banner = `// GENERATED by scripts/gen-en-notes.mjs from pages.ts — do not edit by hand.
// Slim map of the English page sourceNotes (see header comment there for why
// this exists). Re-check drift with: node scripts/gen-en-notes.mjs --check
// (wired into npm run build).
import type { StudioPage } from "./pages";

export const enNotes: Record<string, StudioPage["sourceNotes"]> = {
${entries}
};
`;

const check = process.argv.includes('--check');
if (check) {
	const current = readFileSync(OUT, 'utf8');
	if (current !== banner) {
		console.error('pages-notes-en.ts is stale — run: node scripts/gen-en-notes.mjs');
		process.exit(1);
	}
	console.log('en-notes check: in sync,', pages.filter((p) => p.sourceNotes?.length).length, 'entries');
} else {
	writeFileSync(OUT, banner);
	console.log('en-notes written:', pages.filter((p) => p.sourceNotes?.length).length, 'entries');
}
